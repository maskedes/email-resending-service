import pkg from 'country-codes-list';
const { countryCodes } = pkg;
import { writeFileSync } from 'fs';
import path from 'path';

const rows = pkg
  .all()
  .map((r) => ({
    iso2: r.countryCode,
    name: r.countryNameEn,
    cc: String(r.countryCallingCode).replace(/^\+/, ''),
  }))
  .filter((r) => r.iso2 && r.cc && r.cc.length <= 6)
  .sort((a, b) => a.name.localeCompare(b.name));

const consts = rows.map((r) => `  { iso2: '${r.iso2}', name: ${JSON.stringify(r.name)}, cc: '${r.cc}' },`);

const banner = `// Auto-generated by scripts/gen-countries.mjs (data: country-codes-list).
// Full country list with ISO-2 flags and dial codes. Regenerate instead of hand-editing.
`;

const out = `${banner}export type Country = { iso2: string; name: string; cc: string };\n\nexport const COUNTRIES: Country[] = [\n${consts.join('\n')}\n];\n`;

writeFileSync(path.join('components', 'countries.ts'), out, 'utf8');
console.log(`Wrote ${rows.length} countries.`);
